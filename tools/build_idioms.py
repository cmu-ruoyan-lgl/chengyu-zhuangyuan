    if args.dry_run:
        print("   --dry-run：未写文件")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    print(f"   输出: {OUT}")
    return 0


