TONE = Style.TONE


def make_pinyin(word: str) -> str:
    """生成带声调的拼音，空格分隔。"""
    return " ".join(syl[0] for syl in pinyin(word, style=TONE, heteronym=False))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="只校验不落盘")
    args = ap.parse_args()

    seen: set[str] = set()
    items = []
    problems = []
    for idx, (word, meaning, level, tag) in enumerate(ENTRIES, start=1):
        if len(word) != 4:
            problems.append(f"{word}: 不是四字（{len(word)} 字）")
        if word in seen:
            problems.append(f"{word}: 重复")
        seen.add(word)
        if not meaning:
            problems.append(f"{word}: 释义为空")
        items.append({
            "id": f"i{idx:04d}",
            "word": word,
            "pinyin": make_pinyin(word),
            "meaning": meaning,
            "source": "",
            "example": "",
            "level": level,
            "rare": level == 3,
            "tags": [tag],
        })

    if problems:
        print("❌ 校验失败:")
        for p in problems:
            print("   -", p)
        return 1

    doc = {
        "meta": {
            "version": 1,
            "count": len(items),
            "note": "M1 种子题库，T8 将扩充至 800+ 条 L1 与全量 3800 条",
        },
        "items": items,
    }

    # 交叉可行性体检：统计每个字被多少条成语包含
    char_count: dict[str, int] = {}
    for it in items:
        for ch in set(it["word"]):
            char_count[ch] = char_count.get(ch, 0) + 1
    crossable = sorted(((v, k) for k, v in char_count.items() if v >= 3), reverse=True)
    print(f"✅ 条目数: {len(items)}，唯一汉字: {len(char_count)}")
    print(f"   可交叉字（被 ≥3 条成语包含）: {len(crossable)} 个")
